function bearLike(a, { patch, scarf }) {
  a.group(tilt(-5, 100), () => {
    a.ell(80, 42, 25, 25);
    a.ell(176, 42, 25, 25);
    if (!patch) {
      a.ell(80, 44, 14, 14, { inner: true });
      a.ell(176, 44, 14, 14, { inner: true });
    }
  });
  a.spl([[128, 100], [180, 114], [198, 186], [184, 234], [128, 250], [72, 234], [58, 186], [76, 114]]); // thân nhô lên dưới đầu: không có khe cổ
  a.ell(96, 242, 30, 15);
  a.ell(160, 242, 30, 15);
  // tay ôm sách: mép ngoài tay chìa hẳn ra ngoài thân (không chạy sát mép thân -> không có khe hẹp), sách che đầu tay
  a.spl(tube([[70, 148], [68, 184], [96, 200]], [36, 34, 32]));
  a.spl(tube([[186, 148], [188, 184], [160, 200]], [36, 34, 32]));
  a.shape(rrect(84, 160, 88, 66, 12)); // cuốn sách
  a.line('M128 162 V224', { w: W_OUT });
  a.ell(88, 196, 17, 17);
  a.ell(168, 196, 17, 17);
  if (scarf) a.spl([[74, 128], [128, 146], [182, 128], [186, 150], [128, 166], [70, 150]]);
  a.group(tilt(-5, 100), () => {
    a.spl([[128, 30], [178, 40], [200, 84], [184, 124], [128, 138], [72, 124], [56, 84], [78, 40]]);
    if (patch) {
      a.ell(98, 84, 20, 24, { rot: 0.5, inner: true });
      a.ell(158, 84, 20, 24, { rot: -0.5, inner: true });
    }
    a.ell(128, 108, 30, 22, { inner: true });
    a.ink(ellipsePath(128, 98, 12, 8.5));
    a.line('M128 106 V112');
    a.line('M112 114 Q128 128 144 114', { w: 3 });
    a.eye(98, 82, 13, { dx: 1 });
    a.eye(158, 82, 13, { dx: 1 });
  });
}
