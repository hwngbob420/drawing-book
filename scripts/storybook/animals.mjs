const tilt = (deg, cy = 120) => `rotate(${deg} 128 ${cy})`;
function seated(a, { belly = true, feet = true } = {}) {
  a.spl(BODY);
  if (belly) a.ell(128, 204, 34, 36, { inner: true });
  if (feet) {
    a.ell(100, 240, 30, 16);
    a.ell(156, 240, 30, 16);
  }
}

